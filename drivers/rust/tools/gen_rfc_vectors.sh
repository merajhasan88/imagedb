#!/bin/sh
# Writes tests/rfc_vectors.rs from the RFC texts as published at rfc-editor.org (RFCDIR holds rfcNNNN.txt) and Go's
# sha256_test.go (GOFILE: the Go toolchain's copy on PATH by default), so no test
# vector is typed by hand: each is cut from its RFC by line range, the line cited. Usage: tools/gen_rfc_vectors.sh RFCDIR [GOFILE]
set -eu
RFC=$1
GOFILE=${2:-$(go env GOROOT)/src/crypto/sha256/sha256_test.go}
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=$HERE/../tests/rfc_vectors.rs
F="$HERE/fields.awk"
fields() { awk -v names="$1" -v start="$2" -v end="$3" -f "$F" "$RFC/$4"; }
# joined hex of a line range (spaces removed), e.g. RFC 7914's octet lists
hexlines() { sed -n "$1,$2p" "$RFC/$3" | tr -d ' \n' | tr 'A-F' 'a-f'; }
{
echo "// Generated by tools/gen_rfc_vectors.sh from the RFC texts (rfc-editor.org); do not edit. Each vector names its"
echo "// RFC and the line of its first field there."
echo "#![allow(dead_code)]"
echo
echo "/// RFC 6234 section 8.4's SHA256 table (FIPS 180-4's examples among them): (message, repeat, digest, line)."
echo "pub const SHA256_6234: &[(&[u8], usize, &str, usize)] = &["
# messages from rfc6234.txt lines 5138-5150; digests joined from lines 5425-5442
awk 'NR>=5424 && NR<=5444' "$RFC/rfc6234.txt" | awk '
  /\/\* [0-9]+ \*\// { if (cur != "") print n "\t" cur "\t" at; match($0, /\/\* [0-9]+ \*\//); n = substr($0, RSTART+3, RLENGTH-6) + 0; cur = ""; at = NR + 5423 }
  { s = $0; while (match(s, /"[0-9A-F]+"/)) { cur = cur substr(s, RSTART+1, RLENGTH-2); s = substr(s, RSTART+RLENGTH) } }
  END { print n "\t" cur "\t" at }' | while IFS='	' read -r n d at; do
  d=$(echo "$d" | tr 'A-F' 'a-f')
  case $n in
  1) echo "    (b\"abc\", 1, \"$d\", $at)," ;;
  2) echo "    (b\"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq\", 1, \"$d\", $at)," ;;
  3) echo "    (b\"a\", 1000000, \"$d\", $at)," ;;
  4) echo "    (b\"0123456701234567012345670123456701234567012345670123456701234567\", 10, \"$d\", $at)," ;;
  6) echo "    (b\"\\x19\", 1, \"$d\", $at)," ;;
  esac
done
echo "];"
echo
echo "/// RFC 4231 section 4's test cases 1 to 7: (key, data, HMAC-SHA-256 (case 5: its first 128 bits), line)."
echo "pub const HMAC_4231: &[(&str, &str, &str, usize)] = &["
fields 'Key|Data|HMAC-SHA-256' 170 380 rfc4231.txt | awk -F'\t' '
  $1 == "Key" { k = $2; at = $3 } $1 == "Data" { d = $2 } $1 == "HMAC-SHA-256" { printf "    (\"%s\", \"%s\", \"%s\", %d),\n", k, d, $2, at }'
echo "];"
echo
echo "/// RFC 7914 section 11: PBKDF2-HMAC-SHA-256 (password, salt, iterations, derived key, line)."
echo "pub const PBKDF2_7914: &[(&str, &str, u32, &str, usize)] = &["
L1=$(grep -n 'PBKDF2-HMAC-SHA-256 (P="passwd"' "$RFC/rfc7914.txt" | cut -d: -f1)
L2=$(grep -n 'PBKDF2-HMAC-SHA-256 (P="Password"' "$RFC/rfc7914.txt" | cut -d: -f1)
echo "    (\"passwd\", \"salt\", 1, \"$(hexlines $((L1+2)) $((L1+5)) rfc7914.txt)\", $L1),"
echo "    (\"Password\", \"NaCl\", 80000, \"$(hexlines $((L2+2)) $((L2+5)) rfc7914.txt)\", $L2),"
echo "];"
echo
echo "/// RFC 6234 section 8.4's SHA256 tests 8 and 10, the byte-oriented tests it takes from NIST's SHAVS (its shatest.c:"
echo "/// \"the seven tests documented for each algorithm in SHAVS\"; tests 5, 7 and 9 are bit-level, outside a byte API):"
echo "/// (message hex, digest, line of its #define)."
echo "pub const SHA256_SHAVS_6234: &[(&str, &str, usize)] = &["
for n in 8 10; do
  at=$(grep -n "^#define TEST${n}_256 " "$RFC/rfc6234.txt" | cut -d: -f1)
  msg=$(awk -v at="$at" 'NR < at { next }
    NR > at && /^\f *$|\[Page [0-9]+\] *$|^RFC [0-9]+  |^ *$/ { next }
    NR > at { s = $0; while (match(s, /\\x[0-9a-fA-F][0-9a-fA-F]/)) { printf "%s", tolower(substr(s, RSTART + 2, 2)); s = substr(s, RSTART + RLENGTH) }
              if ($0 !~ /\\ *$/) exit }' "$RFC/rfc6234.txt")
  # its digest: the table's entry /* n */ under SHA256 (lines 5424-5453), the quoted hex joined
  dg=$(awk 'NR>=5424 && NR<=5453' "$RFC/rfc6234.txt" | awk -v n="$n" '
    /\/\* [0-9]+ \*\// { match($0, /\/\* [0-9]+ \*\//); cur = substr($0, RSTART+3, RLENGTH-6) + 0 }
    cur == n && !done { s = $0; while (match(s, /"[0-9A-F]+"/)) { d = d substr(s, RSTART+1, RLENGTH-2); s = substr(s, RSTART+RLENGTH) }
                         if ($0 ~ /}/) done = 1 }
    END { print tolower(d) }')
  echo "    (\"$msg\", \"$dg\", $at),"
done
echo "];"
echo
echo "/// Go's crypto/sha256 golden table (go/src/crypto/sha256/sha256_test.go, its \"golden\" table, lines 26 to 56; GOFILE),"
echo "/// messages of 0 to 132 bytes, the empty one among them: (message, digest, line). Entries holding an escape are left out."
echo "pub const SHA256_GO: &[(&[u8], &str, usize)] = &["
awk 'NR >= 26 && NR <= 57 && /^\t\{"[0-9a-f]{64}", "/ {
       d = substr($0, 4, 64); rest = substr($0, 72)
       i = index(rest, "\""); m = substr(rest, 1, i - 1)
       if (m ~ /\\/) next
       printf "    (b\"%s\", \"%s\", %d),\n", m, d, NR }' "$GOFILE"
echo "];"
} > "$OUT"
echo "wrote $OUT"
# Phase 2's vectors (TLS: RFC 7748, 8439, 6979, 8448, 5903, 5869's HKDF) are stage 2's: parked-tls-unreviewed/orig-20261119/tools/.
